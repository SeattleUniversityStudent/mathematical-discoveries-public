import json,sys
polys={tuple(map(int,k.split(','))):v for k,v in json.load(open('polys.json')).items()}
def P(c, j='j'):
    terms=[]
    for t,a in enumerate(c):
        if a==0: continue
        mon = '1' if t==0 else (f'({j}:Int)' if t==1 else f'({j}:Int)^{t}')
        terms.append(f'({a}:Int)*{mon}')
    return ' + '.join(terms) if terms else '0'
def name(par,s,p): return f"st_{'o' if par else 'e'}{s}_{p}"
ev=sorted(k for k in polys if k[0]==0); od=sorted(k for k in polys if k[0]==1)
def stmt(par,s,p,j='j'):
    k = f'2*{j}' if par==0 else f'2*{j}+1'
    b = f'3*{j}' if par==0 else f'3*{j}+1'
    n = b if s==0 else f'{b}+{s}'
    return f'(24 * (F ({k}) ({n}) {p} : Nat) : Int) = {P(polys[(par,s,p)],j)}'
out=["import CarlitzCore","","/-! Generated by gen/gen.py. Closed forms for F at slack ≤ 4, by induction on j. -/",""]
out.append("def EvenOK (j : Nat) : Prop :=\n  " + " ∧\n  ".join(stmt(*st) for st in ev))
out.append("def OddOK (j : Nat) : Prop :=\n  " + " ∧\n  ".join(stmt(*st) for st in od))
def step(par_next, s, p, prev_states):
    d = 1 if par_next==1 else 2
    L = d+s
    if par_next==1:
        hdr=f"theorem {name(1,s,p)} (j : Nat) (hj : 2 ≤ j) (h : EvenOK j) : {stmt(1,s,p)} := by"
        kprev='2*j'; nprev=(f'3*j+1+{s}' if s else '3*j+1'); nb=f'3*j'  # prev base
        lhs_rw = ""
    else:
        hdr=f"theorem {name(0,s,p)} (j : Nat) (hj : 2 ≤ j) (h : OddOK j) : {stmt(0,s,p,'(j+1)')} := by"
        kprev='2*j+1'; nprev=(f'3*j+3+{s}' if s else '3*j+3'); nb=f'3*j+1'
        lhs_rw = f"  rw [show 2*(j+1) = (2*j+1)+1 by omega, show {'3*(j+1)' if s==0 else f'3*(j+1)+{s}'} = {'3*j+3' if s==0 else f'3*j+3+{s}'} by omega]\n"
    lines=[hdr, "  unfold " + ("EvenOK" if par_next==1 else "OddOK") + " at h"]
    names=[name(*st) for st in prev_states]
    need=set()
    for i in range(L):
        q=i+1
        if q==p: continue
        need.add((1-par_next, d+s-q, q))
    lines.append("  obtain ⟨" + ", ".join(("h_"+name(*st)) if st in need else "-" for st in prev_states) + "⟩ := h")
    if lhs_rw: lines.append(lhs_rw.rstrip())
    lines.append("  rw [F]")
    lines.append(f"  rw [sum_range_trunc _ {L} _ (by omega) (fun i h1 h2 => by")
    lines.append(f"    split")
    lines.append(f"    · rfl")
    lines.append(f"    · refine F_vanish _ _ _ ?_")
    lines.append(f"      unfold minsum; (repeat' split) <;> omega)]")
    lines.append("  simp only [List.range_succ, List.range_zero, List.nil_append, List.map_append, List.map_cons, List.map_nil, List.sum_append, List.sum_cons, List.sum_nil]")
    # rewrite each term's n - (i+1)
    rws=[]
    for i in range(L):
        q=i+1
        if q==p: continue
        sp = d+s-q
        rws.append(f"show {nprev} - ({i} + 1) = " + (nb if sp==0 else f"{nb}+{sp}") + " by omega")
    if rws: lines.append("  simp only [" + ", ".join(rws) + "]")
    lines.append("  simp only [Nat.reduceAdd, Nat.reduceEqDiff, ite_true, ite_false, Nat.add_zero, Nat.zero_add, reduceIte]")
    lines.append("  push_cast")
    lines.append("  grind")
    return "\n".join(lines)
open('../CarlitzStates.lean','w').write("\n\n".join(out)+"\n")
steps=[step(1, st[1], st[2], ev) for st in od]+[step(0, st[1], st[2], od) for st in ev]
files=[]
for c in range(0,len(steps),5):
    fn=f"CarlitzSteps{c//5}"
    open(f'../{fn}.lean','w').write("import CarlitzStates\n\n"+"\n\n".join(steps[c:c+5])+"\n")
    files.append(fn)
open('../CarlitzSteps.lean','w').write("".join(f"import {f}\n" for f in files))
print(files)
